sbox = np.array(sbox, dtype=np.uint8)


# csv Datei lesen + daten laden
def load_data(file):
    plaintexts = []
    times = []
    with open(file, "r") as f:
        reader = csv.reader(f)
        for row in reader:
            # 16 bytes plaintext + 1 time
            plaintexts.append([int(x) for x in row[:16]])
            times.append(row[16])
    # pt und time arrays
    return np.array(plaintexts, dtype=np.uint8), np.array(times,dtype=np.float64)

# t-test
def t_value_computation(plaintexts, times, byte_index):
    # für einen byte_index die t-werte aller 256 key-guesses berechnen
    t_values = np.zeros(256)

    for k in range(256):
        # sbox[pt XOR k]
        sbox_out = sbox[plaintexts[:, byte_index] ^ k]
        # MSB (bit 7)
        MSB = (sbox_out >> 7) & 1 #ausschl. letztes bit

        # boolean indexing
        group0 = times[MSB == 0]
        group1 = times[MSB == 1]

        mean0 = np.mean(group0)
        mean1 = np.mean(group1)

        var0 = np.var(group0, ddof = 1) # Stichprobenvarianz
        var1 = np.var(group1, ddof = 1)

        t_values[k] = (mean1 - mean0) / np.sqrt(var0/len(group0) + var1/len(group1))

    return t_values

def key_recovery(plaintexts, times):
    key = []
    all_t_values=[]

    start = time.perf_counter()

    for b in range(16):
        t_vals = t_value_computation(plaintexts, times, b)
        best_k = np.argmax(np.abs(t_vals))
        key.append(best_k)
        all_t_values.append(t_vals)

    key_decimal = [int(x) for x in key]
    key_hex = [f"{x:02X}" for x in key]

    with open("key.txt", "w") as f:
        f.write("Decimal: " + " ".join(map(str, key_decimal)) + "\n")
        f.write("Hex: " + " ".join(key_hex) + "\n")

    runtime = time.perf_counter() - start
    print(f"\nLaufzeit Key-Recovery: {runtime:.2f} Sekunden")

    # plot t-werte pro key-guess
    for b in range(16):
        plt.figure(figsize=(10, 4))
        plt.plot(range(256), all_t_values[b], color="purple")

        plt.xlabel("Key Guess")
        plt.ylabel("t-value")
        plt.title(f"Byte {b}: t-test")
        plt.grid(alpha=0.3)

        plt.tight_layout()
        plt.savefig(f"plot_k_t_{b:02d}.png")
        plt.close()

    # Plot t-wert vs. # traces
    step = 10000 #schritte von 10.000
    max_n = len(times)
    ns = list(range(step, max_n+1, step))

    print("# traces:", max_n)
    print("ns:", len(ns))

    for b in range(16):
        print(f"  Byte {b} ...", end=" ", flush=True)
        t_over_n = []
        for n in ns:
            t_vals = t_value_computation(plaintexts[:n], times[:n], b)
            t_over_n.append(t_vals)
        t_over_n = np.array(t_over_n)
        

        plt.figure(figsize=(11,5))
        for k in range(256):
            if k == key[b]:
                plt.plot(ns, t_over_n[:, k], "r-", linewidth=2.2, label=f"correct key 0x{key[b]:02X}")
            else: 
                plt.plot(ns, t_over_n[:, k], "b-", alpha=0.12, linewidth=0.6)
        plt.xlabel("# traces")
        plt.ylabel("t-value")
        plt.title(f"Byte {b} - t-value vs. # traces")
        plt.legend()
        plt.grid(True, alpha=0.3)
        plt.tight_layout()
        
        plt.savefig(f"plot_nrtraces_t_{b:02d}.png", dpi=120)
        plt.close()
        print("fertig")

    return key, runtime

